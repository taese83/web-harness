#!/usr/bin/env node

import {existsSync, realpathSync} from 'node:fs'
import {basename, dirname, join, resolve} from 'node:path'
import {validateReleaseGate} from './release-gate-lib.mjs'

const readInput = async () => {
  let source = ''
  for await (const chunk of process.stdin) source += chunk
  return JSON.parse(source)
}

const block = message => {
  process.stderr.write(`${message}\n`)
  process.exit(2)
}

const canonicalPotentialPath = targetPath => {
  let existingPath = targetPath
  const missingSegments = []
  while (!existsSync(existingPath)) {
    const parentPath = dirname(existingPath)
    if (parentPath === existingPath) break
    missingSegments.unshift(basename(existingPath))
    existingPath = parentPath
  }
  return join(realpathSync(existingPath), ...missingSegments)
}

try {
  const input = await readInput()
  if (!['Write', 'Edit'].includes(input.tool_name)) process.exit(0)

  const filePath = input.tool_input?.file_path
  if (typeof filePath !== 'string') process.exit(0)

  const absolutePath = canonicalPotentialPath(resolve(filePath))
  const normalizedPath = absolutePath.split('\\').join('/')
  if (
    normalizedPath.includes('/_workspace/04_qa/evidence/') ||
    normalizedPath.endsWith('/_workspace/04_qa/qa-manifest.json')
  ) {
    block('Blocked: machine receipts and qa-manifest.json must be generated by the quality/release gate scripts.')
  }

  const releaseDirectory = dirname(absolutePath)
  const workspaceDirectory = dirname(releaseDirectory)
  // .at(-1)은 Node 16.6+ — 구버전 Node에서 hook이 crash로 fail-close되지 않도록 마지막 요소를 직접 취한다.
  const lastSegment = value => {
    const segments = value.split('/')
    return segments[segments.length - 1]
  }
  if (
    lastSegment(absolutePath) !== 'HANDOFF.md' ||
    lastSegment(releaseDirectory) !== 'RELEASE' ||
    lastSegment(workspaceDirectory) !== '_workspace'
  ) {
    process.exit(0)
  }

  const projectRoot = dirname(workspaceDirectory)
  const {errors} = validateReleaseGate(projectRoot)
  if (errors.length > 0) {
    block(`Blocked: HANDOFF requires a passing release gate. ${errors.join(' | ')}`)
  }
} catch (error) {
  block(`Blocked: release gate hook could not validate the operation: ${error instanceof Error ? error.message : String(error)}`)
}
